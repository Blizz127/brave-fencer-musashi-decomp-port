#!/usr/bin/env python3
"""Find function starts in a raw overlay so splat can label them.

Without symbols splat labels only what it can infer, which on MAIN.CD member
0007 was 2 functions out of 19. Member 0012 is far larger, so it needs real
symbol input before its code is reachable.

Two sources are combined, and both are necessary:

* **Stack-frame prologues.** `addiu $sp, $sp, -N` opens a frame, so it marks a
  function start. This misses every frameless leaf, which never touches $sp.
* **Call targets.** A `jal` encodes an absolute address, so anything called is a
  function start by definition. This is what recovers the frameless leaves, and
  it is why the load address for this member verified at only 72% against
  prologues alone: prologue count is a floor, not the function count.

Targets outside the member are calls into the executable or another overlay and
are deliberately excluded; they are not this member's symbols.
"""

from __future__ import annotations

import argparse
import struct
import sys
from pathlib import Path

from retail_common import RetailError

WORD = 4
SP_REGISTER = 29
OPCODE_ADDIU = 9
OPCODE_JAL = 3
NEGATIVE_IMMEDIATE = 0x8000
KSEG0 = 0x80000000


def _words(data: bytes):
    for offset in range(0, len(data) - (len(data) % WORD), WORD):
        yield offset, struct.unpack_from("<I", data, offset)[0]


def find_prologue_offsets(data: bytes) -> list[int]:
    """Offsets of `addiu $sp, $sp, -N`, which opens a stack frame.

    A positive adjustment tears a frame down and is an epilogue, so only
    negative immediates count.
    """

    offsets = []
    for offset, word in _words(data):
        if word >> 26 != OPCODE_ADDIU:
            continue
        rs = (word >> 21) & 0x1F
        rt = (word >> 16) & 0x1F
        immediate = word & 0xFFFF
        if rs == SP_REGISTER and rt == SP_REGISTER and immediate >= NEGATIVE_IMMEDIATE:
            offsets.append(offset)
    return offsets


def find_jal_targets(data: bytes) -> list[int]:
    """Absolute addresses called by `jal`, deduplicated and sorted."""

    targets = set()
    for _offset, word in _words(data):
        if word >> 26 == OPCODE_JAL:
            targets.add(KSEG0 | ((word & 0x03FFFFFF) << 2))
    return sorted(targets)


def discover_function_starts(data: bytes, base: int, from_offset: int = 0) -> list[int]:
    """Absolute addresses of function starts in the region beginning at `from_offset`.

    `base` addresses that region's first byte, not the file's. A member may be a
    container with data chunks ahead of the code; scanning those would invent
    function starts from bytes that merely happen to look like a prologue.
    """

    if not data:
        raise RetailError("member is empty")
    if base % WORD:
        raise RetailError(f"load base 0x{base:08X} is not word-aligned")
    if from_offset % WORD:
        raise RetailError(f"region offset {from_offset} is not word-aligned")
    if from_offset >= len(data):
        raise RetailError(f"region offset {from_offset} is past the member end {len(data)}")

    region = data[from_offset:]
    starts = {base + offset for offset in find_prologue_offsets(region)}
    end = base + len(region)
    starts.update(target for target in find_jal_targets(region) if base <= target < end)
    return sorted(starts)


def render_symbol_addrs(addresses: list[int]) -> str:
    """Render splat's symbol_addrs syntax."""

    lines = [
        "// Generated by tools/discover_symbols.py from stack-frame prologues and",
        "// jal targets. Names are provisional and encode the address.",
    ]
    lines += [f"func_{address:08X} = 0x{address:08X}; // type:func" for address in addresses]
    return "\n".join(lines) + "\n"


def build_parser() -> argparse.ArgumentParser:
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("member", type=Path, help="raw overlay member, e.g. extracted/overlays/main/0012.bin")
    parser.add_argument("--base", required=True, help="load address of the region's first byte")
    parser.add_argument("--from-offset", default="0", help="file offset where the code region starts")
    parser.add_argument("--output", type=Path, required=True, help="symbol_addrs file to write")
    return parser


def main(argv: list[str] | None = None) -> int:
    args = build_parser().parse_args(argv)
    try:
        if not args.member.is_file():
            raise RetailError(f"member not found: {args.member}")
        try:
            base = int(str(args.base), 0)
        except ValueError as exc:
            raise RetailError(f"could not parse --base: {exc}") from exc

        try:
            from_offset = int(str(args.from_offset), 0)
        except ValueError as exc:
            raise RetailError(f"could not parse --from-offset: {exc}") from exc

        data = args.member.read_bytes()
        prologues = len(find_prologue_offsets(data[from_offset:]))
        starts = discover_function_starts(data, base, from_offset)
        args.output.parent.mkdir(parents=True, exist_ok=True)
        args.output.write_text(render_symbol_addrs(starts), encoding="utf-8")

        print(f"DISCOVERED {len(starts)} function starts in {args.member.name}")
        print(f"  region: file 0x{from_offset:X}..0x{len(data):X}")
        print(f"  vram:   0x{base:08X}..0x{base + len(data) - from_offset:08X}")
        print(f"  from prologues: {prologues}")
        print(f"  added by call targets (frameless leaves): {len(starts) - prologues}")
        print(f"  output={args.output}")
        return 0
    except RetailError as exc:
        print(f"discover_symbols: ERROR: {exc}", file=sys.stderr)
        return 2


if __name__ == "__main__":
    raise SystemExit(main())
